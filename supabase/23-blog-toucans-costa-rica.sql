## 1. How many species of toucans live in Costa Rica?

Costa Rica is home to six species of the family Ramphastidae, which includes both the large toucans and the smaller toucanets and aracaris. Here are the ones you are most likely to encounter:

### Keel-billed Toucan

Scientific name: *Ramphastos sulfuratus*.

This is probably the most recognizable toucan in Costa Rica. Its enormous bill blends yellow, green, orange, blue and red, while its body is mostly black, with a bright yellow chest and a red patch under the tail.

It lives mainly in humid tropical forests, secondary forests and wooded areas, and it often visits gardens and properties surrounded by vegetation. In La Fortuna and around Arenal Volcano it is one of the species visitors have a very good chance of seeing on a nature tour.

### Yellow-throated Toucan (Chestnut-mandibled Toucan)

Scientific name: *Ramphastos ambiguus swainsonii*.

This is one of the largest toucans found in Costa Rica. Its huge bill has a yellow upper mandible and a chestnut-brown lower mandible. Its dark body and yellow chest with a red band make it a spectacular subject for wildlife photography.

It is found mainly in humid lowland forests and in the lower mountain slopes, where it moves from tree to tree in search of fruit. Its far-carrying call, often described as "Dios te dé" by Costa Ricans, is one of the classic sounds of the rainforest at dawn.

### Collared Aracari

Scientific name: *Pteroglossus torquatus*.

Unlike the large toucans, the Collared Aracari is smaller and usually travels in noisy groups of several birds. Its bill combines yellow, black and reddish tones, and its plumage mixes black, yellow and red.

It is an active species that can be seen moving through the trees, feeding on fruit and insects, and it is a frequent visitor to fruiting trees near trails and gardens.

### Fiery-billed Aracari

Scientific name: *Pteroglossus frantzii*.

This species is especially interesting because it is found only in the southern Pacific region of Costa Rica and western Panama. Its bill displays a combination of orange, red and yellow, and its plumage has very striking patterns.

If you visit the southern Pacific coast, you will have good opportunities to look for this beautiful aracari.

### Northern Emerald-Toucanet

Scientific name: *Aulacorhynchus prasinus*.

This is one of the most beautiful toucanets of the mountains. Its plumage is mostly green, its bill is relatively small and its throat is bluish. Unlike the large toucans, it often goes unnoticed among the leaves thanks to its coloration.

It can be found in cloud forests and higher elevations, including the forests of Monteverde and the mountain ranges of Costa Rica.

### Yellow-eared Toucanet

Scientific name: *Selenidera spectabilis*.

This is one of the hardest species to observe. It lives mainly in the humid forests of the Caribbean slope and the mountain foothills. Its most distinctive feature is the yellow patch behind the eye, especially visible in males.

Finding it requires patience, knowledge of its calls and, ideally, the company of an experienced naturalist guide.

Together, these species make Costa Rica an exceptional destination for anyone interested in birdwatching.

## 2. Where to find toucans in Costa Rica

One of the advantages of visiting Costa Rica is that you do not need to hike for hours into a remote forest to see a toucan. They are often found near nature trails, farms, tropical gardens and protected areas. These are some of the best destinations to look for them:

### La Fortuna and Arenal Volcano National Park

The La Fortuna region is one of the most rewarding destinations for toucan watching in Costa Rica. Its tropical forests, biological corridors and abundance of fruiting trees provide excellent conditions for several species.

On a birdwatching tour it is possible to look for the Keel-billed Toucan, the Yellow-throated Toucan and the Collared Aracari. The area around Arenal also lets you combine toucans with sloths, monkeys, hummingbirds and many other wildlife species in a single outing.

### Sarapiquí

Sarapiquí is internationally known for its biodiversity and its humid tropical forests. It is an excellent destination for toucans, aracaris and many other resident birds. Its private reserves, trails and biological stations offer great opportunities for nature photographers.

### Tortuguero

The forests and canals of Tortuguero provide ideal habitat for a huge number of bird species. The Keel-billed Toucan is one of the stars of this region, and scanning the treetops during a boat ride can lead to unforgettable encounters.

### Osa Peninsula

The southern Pacific holds some of the most impressive tropical forests in Costa Rica. This region is especially interesting for the Yellow-throated Toucan and the Fiery-billed Aracari.

### Monteverde

If you want to see the Northern Emerald-Toucanet, the cloud forests of Monteverde are an excellent choice. The elevation and climate support species that are different from those of the lowlands.

## 3. What is the best time of day to see toucans?

Toucans can be seen all year round in Costa Rica, but there are times of day when your chances improve considerably.

**Early morning, from 5:30 a.m. to 8:30 a.m.** This is one of the most productive periods for tropical birdwatching. Toucans move between trees looking for food, call frequently and take advantage of the first hours of light.

**Afternoon, from 2:30 p.m. to 5:00 p.m.** This is also a good window. Many birds become active again as they travel between feeding and roosting areas.

One important tip: do not focus only on walking the trails. Sometimes spending several minutes watching a tree loaded with fruit produces better results than covering long distances.

## 4. Tips for finding toucans in their natural habitat

If you want to improve your chances of seeing toucans during your vacation in Costa Rica, keep these tips in mind:

**1. Learn to recognize their calls.** Toucans have distinctive calls that carry over long distances. Learning to recognize them helps you detect their presence even when they are hidden in the canopy.

**2. Watch fruiting trees.** Toucans feed mainly on fruit and return again and again to trees that offer food. Pay attention to cecropia (guarumo), fig trees, palms and other native species in fruit.

**3. Look up into the canopy.** One of the most common mistakes visitors make is looking only at eye level. Toucans spend much of their time in the middle and upper layers of the forest.

**4. Walk slowly and quietly.** Sudden movements and loud conversation make observation harder. Walking slowly and stopping often reveals birds that at first went unnoticed.

**5. Use binoculars or a spotting scope.** Binoculars are excellent for locating toucans among the branches. If you are interested in bird photography, a telephoto lens lets you capture the details of their bills and plumage without getting too close.

**6. Go with a local naturalist guide.** An experienced guide knows the sounds, behaviors and habitats of each species, and can point you to feeding trees and places where toucans have been seen recently. Birdwatching is not only about finding animals, but also about understanding their behavior and their relationship with the ecosystem.

**7. Be patient and respect wildlife.** No walk can guarantee a sighting. Avoid chasing birds, approaching their nests or repeatedly playing recorded calls to attract them. The best photograph is the one that does not alter the animal's natural behavior.

## 5. Why do toucans have such large bills?

The toucan's bill is one of its most extraordinary features. Although it looks heavy, it is made of a light structure with an internal network of supports. It serves several purposes:

- **Feeding:** it allows the bird to reach fruit on thin branches that would not support its weight.
- **Temperature regulation:** blood flow through the bill helps the toucan release body heat.
- **Defense:** it can be used to intimidate other animals.
- **Social interaction:** it plays a role in communication and courtship.

Toucans also play a very important ecological role: they disperse seeds throughout the tropical forest and help its natural regeneration.

## 6. What is the best time of year to see toucans in Costa Rica?

Good news for travelers: toucans are resident birds, so they can be seen all year round. You do not need to travel exclusively during the dry season to find them.

During the green season, the abundance of fruit and the breeding activity of many species offer excellent observation opportunities. During the dry season, trails tend to be more accessible and the weather makes walks more comfortable.

My recommendation is to plan your outings early in the morning and choose areas with dense vegetation and fruiting trees.

