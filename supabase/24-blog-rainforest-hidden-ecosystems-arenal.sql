Debajo del dosel encontramos un ambiente con mucha menos iluminación. Este nivel está compuesto por árboles pequeños, palmeras, plantas jóvenes, helechos y enredaderas que se han adaptado a vivir con poca luz. También es un espacio importante para observar las relaciones entre plantas, insectos y animales.

### El suelo del bosque

En el suelo encontramos hojas, ramas, frutos y materia orgánica que forman parte de un proceso natural fundamental. Los hongos, insectos y microorganismos descomponen estos materiales y devuelven sus nutrientes al suelo, lo que favorece el crecimiento de nuevas plantas.

