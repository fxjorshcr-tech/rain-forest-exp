### Bromelias

Las bromelias son particularmente fascinantes porque algunas especies acumulan agua entre sus hojas y forman pequeños ambientes acuáticos. Estos espacios pueden servir de hábitat para larvas de insectos, pequeñas ranas y otros organismos.

### Plantas epífitas

Son plantas que crecen sobre otras plantas, especialmente en los troncos y ramas de los árboles, sin extraer nutrientes del árbol que las sostiene. Las orquídeas, las bromelias y algunos helechos son buenos ejemplos. Utilizan la estructura del bosque para alcanzar la luz y obtienen la humedad del ambiente.

### Helechos y musgos

Son especialmente comunes en ambientes húmedos. Contribuyen a la estructura del bosque, proporcionan pequeños hábitats y ayudan a conservar la humedad.

Observar de cerca la vegetación permite comprender cómo diferentes especies aprovechan el mismo espacio de distintas maneras.

