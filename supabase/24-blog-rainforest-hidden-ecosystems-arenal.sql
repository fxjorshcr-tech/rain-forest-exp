## 1. The rainforest is a world of different levels

One of the most interesting features of tropical forests is their vertical structure. The forest is not simply a uniform group of trees: it is organized in levels, each with its own environmental conditions and habitats.

### The emergent layer

It is made up of the tallest trees, which rise above the rest of the forest and receive direct sunlight. These trees provide habitat and shelter for different species of birds and other organisms adapted to living in the highest parts of the forest.

### The canopy

The canopy forms a kind of natural roof over the rainforest. It is a zone with abundant sunlight and a great diversity of organisms: birds, insects, orchids, bromeliads and countless climbing plants.

For nature lovers, looking carefully at the treetops is one of the most rewarding things to do on a walk through the tropical forest.

### The understory

Beneath the canopy we find an environment with much less light. This level is made up of small trees, palms, young plants, ferns and vines that have adapted to living in the shade. It is also an important place to observe the relationships between plants, insects and animals.

### The forest floor

On the ground we find leaves, branches, fruits and organic matter that are part of an essential natural process. Fungi, insects and microorganisms break these materials down and return their nutrients to the soil, supporting the growth of new plants.

Each level plays an important role in keeping the ecosystem in balance.

## 2. The smallest organisms do enormous jobs

When we walk through the rainforest, it is very easy to focus our attention on the largest and most striking animals. However, some of the most important ecological processes happen at a much smaller scale.

Fungi, insects and microorganisms are essential components of tropical ecosystems. Fungi take part in the decomposition of organic matter, while many insects contribute to pollination, seed dispersal and nutrient recycling.

Ants, for example, play different roles depending on the species. Leafcutter ants carry pieces of leaves to their nest to grow the fungus they feed on, others help recycle organic matter, and some maintain close ecological relationships with plants and other organisms.

Even a small pile of fallen leaves can hold an entire community of living things. That is why walking slowly and looking carefully can turn a forest walk into a much richer experience. The rainforest is full of small details that often go unnoticed when we are only looking for large animals.

## 3. How plants sustain an entire community of life

Plants are much more than the green background of a tropical landscape. They provide food, shelter, nesting sites and essential resources for countless organisms. In the Arenal region we can find several very interesting groups of tropical plants.

### Bromeliads

Bromeliads are particularly fascinating because some species collect water between their leaves, creating small aquatic environments. These tiny pools can become a habitat for insect larvae, small frogs and other organisms.

### Epiphytes

Epiphytes are plants that grow on other plants, especially on the trunks and branches of trees, without taking nutrients from the tree that supports them. Orchids, bromeliads and some ferns are good examples. They use the structure of the forest to reach the light and get their moisture from the environment.

### Ferns and mosses

They are especially common in humid environments. They add to the structure of the forest, provide small habitats and help retain moisture.

Looking closely at the vegetation helps us understand how different species make use of the same space in different ways.

