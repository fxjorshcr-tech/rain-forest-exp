## 5. ¿Por qué los tucanes tienen picos tan grandes?

El pico de los tucanes es una de sus características más extraordinarias. Aunque parece pesado, está formado por una estructura ligera con una red interna de soporte. Cumple varias funciones:

- **Alimentación:** les permite alcanzar frutos en ramas delgadas que no soportarían su peso.
- **Regulación de la temperatura:** el flujo sanguíneo del pico ayuda a disipar el calor corporal.
- **Defensa:** puede utilizarse para intimidar a otros animales.
- **Interacción social:** forma parte de sus comportamientos de comunicación y cortejo.

Además, los tucanes desempeñan un papel ecológico muy importante: dispersan semillas a través de los bosques tropicales y contribuyen a su regeneración natural.

