Una de las características más interesantes de los bosques tropicales es su estructura vertical. El bosque no es simplemente un conjunto uniforme de árboles: está organizado en niveles, cada uno con condiciones ambientales y hábitats particulares.

### El estrato emergente

Está formado por los árboles más altos, que sobresalen por encima del resto del bosque y reciben directamente la luz solar. Estos árboles sirven de hábitat y refugio para diferentes especies de aves y otros organismos adaptados a vivir en las partes más altas.

